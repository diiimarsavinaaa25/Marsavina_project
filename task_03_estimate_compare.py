# 1. Задать температуру в °C
cel = 25

# 2. Перевести в °F
f = cel * 9/5 + 32

# 3. Определить состояние воды
if cel <= 0:
    state = "Лёд"
elif cel >= 100:
    state = "Пар"
else:
    state = "Жидкость"

# 4. Вывод результатов
print(f"Температура в °C: {cel}°C")
print(f"Температура в °F: {round(f, 2)}°F")
print(f"Состояние воды: {state}")