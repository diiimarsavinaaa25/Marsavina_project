# 1. Создать 3 списка материалов (от трёх подрядчиков)
contractor_1 = ["Цемент", "Кирпич", "Песок", "Щебень", "Гравий"]
contractor_2 = ["Кирпич", "Песок", "Арматура", "Бетон", "Профнастил"]
contractor_3 = ["Цемент", "Песок", "Щебень", "Доска", "Рубероид"]
# 2. Преобразовать списки во множества
set1 = set(contractor_1)
set2 = set(contractor_2)
set3 = set(contractor_3)
# 3. Найти все уникальные материалы (объединение)
all = set1 | set2 | set3
print("Все уникальные материалы:", all)
# 4. Общие для всех (пересечение)
common_all = set1 & set2 & set3
print("Общие для всех:", common_all)
# 5. Только у первого (разность)
only_first = set1 - set2 - set3
print("Только у первого подрядчика:", only_first)
# 6. Ровно у двух (симметричная разница или комбинация)
# Материалы которые есть ровно в двух списках
in_1_and_2 = set1 & set2 - set3
in_1_and_3 = set1 & set3 - set2
in_2_and_3 = set2 & set3 - set1
exactly_two = in_1_and_2 | in_1_and_3 | in_2_and_3
print("Ровно у двух подрядчиков:", exactly_two)