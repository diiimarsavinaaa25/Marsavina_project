# 1. Создать список из 5 материалов
materials = ["Цемент", "Кирпич", "Песок", "Щебень", "Арматура"]
print("Исходный список:", materials)
# 2. Вывести первый, последний, средние элементы
print(f"Первый элемент: {materials[0]}")
print(f"Последний элемент: {materials[-1]}")
print(f"Средние элементы: {materials[1:-1]}")
# 3. Добавить 2 новых материала
materials.append("Бетон")
materials.append("Доска")
print("После добавления:", materials)
# 4. Удалить второй элемент (индекс 1)
removed = materials.pop(1)
print(f"Удален элемент: {removed}")
# 5. Вывести итоговый список и длину
print("Итоговый список:", materials)
print(f"Длина списка: {len(materials)}")