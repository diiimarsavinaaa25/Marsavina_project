# 1. Задать цену и количество товара
price = 1200  # цена за единицу
q = 5  # количество
# 2. Рассчитать общую стоимость до скидки
total = price * q
print(f"Стоимость до скидки: {total} руб")
# 3. Определить процент скидки
if total < 1000:
    percent = 0
elif total <= 5000:
    percent = 5
else:
    percent = 10
print(f"Скидка: {percent}%")
# 4. Рассчитать сумму скидки
a = total * percent / 100
print(f"Сумма скидки: {a} руб")
# 5. Рассчитать итоговую стоимость
final = total - a
print(f"Итоговая стоимость: {final} руб")